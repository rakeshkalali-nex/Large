const immutable = ['issue_events','review_decisions','stock_transactions','stock_entries','cost_recognitions','allocations','financial_reversals','payment_refund_sources','property_price_history','lead_activities','payment_verifications','payment_verification_allocations','handovers','audit_events','idempotency_records','policy_acknowledgments','duplicate_reviews','duplicate_review_invoices','reconciliation_lines','reconciliation_reviews','report_snapshots'];
sql = '-- Generated immutable-history guards. Compensation is an INSERT, never an edit.\n';
for (const table of immutable) {
  for (const action of ['UPDATE', 'DELETE']) sql += `CREATE TRIGGER ${table}_no_${action.toLowerCase()} BEFORE ${action} ON ${table} BEGIN SELECT RAISE(ABORT,'${table} is append-only'); END;\n`;
}
// Immutable submitted revision snapshots: approval changes the revision header,
// never the historical detail rows. Corrections create another revision.
for (const table of ['purchase_order_revision_lines', 'work_order_revision_milestones', 'plan_revision_milestones']) {
  for (const action of ['UPDATE', 'DELETE']) sql += `CREATE TRIGGER ${table}_no_${action.toLowerCase()} BEFORE ${action} ON ${table} BEGIN SELECT RAISE(ABORT,'revision snapshot is immutable'); END;\n`;
}
for (const [table,parent,column] of [['invoice_lines','invoices','invoice_id'],['goods_receipt_lines','goods_receipts','goods_receipt_id'],['budget_lines','budget_revisions','revision_id'],['cancellation_bands','cancellation_terms','terms_id']]) {
  const editable = table === 'cancellation_bands' ? "'submitted'" : "'draft'";
  for (const action of ['INSERT','UPDATE','DELETE']) {
    const row = action === 'DELETE' ? 'OLD' : 'NEW';
    let condition = `(SELECT status FROM ${parent} WHERE id=${row}.${column}) NOT IN (${editable})`;
    if (action === 'UPDATE') condition += ` OR (SELECT status FROM ${parent} WHERE id=OLD.${column}) NOT IN (${editable})`;
    sql += `CREATE TRIGGER ${table}_locked_${action.toLowerCase()} BEFORE ${action} ON ${table} WHEN ${condition} BEGIN SELECT RAISE(ABORT,'approved or posted detail is immutable'); END;\n`;
  }
}
