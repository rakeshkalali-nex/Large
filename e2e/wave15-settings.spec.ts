import { test, expect } from '../tests/integration/auth-entry/fixtures';

test('Administrator completes explicit company setup and sees persisted history and healthy operator status',async ({page,accountServer})=>{
  await page.goto('/login?returnUrl=%2Fsettings');
  await page.getByLabel('Email address').fill(accountServer.email);
  await page.getByLabel('Password',{exact:true}).fill(accountServer.password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Company settings',exact:true})).toBeVisible();
  await expect(page.getByText('Operational setup is incomplete.')).toBeVisible();
  await expect(page.getByLabel('Base currency (ISO code)')).toHaveValue('');
  await expect(page.getByRole('textbox',{name:/^Company timezone IANA/})).toHaveValue('UTC');
  await expect(page.getByRole('checkbox',{name:'I confirm this company timezone'})).not.toBeChecked();
  await page.getByLabel('Base currency (ISO code)').fill('USD');
  await page.getByRole('checkbox',{name:'I confirm this company timezone'}).check();
  await page.getByLabel('Operating countries (two-letter codes, comma separated)').fill('US');
  await page.getByLabel('Approved privacy notice version').fill('test-notice-v1');
  await page.getByLabel('Approved retention schedule version').fill('test-retention-v1');
  await page.getByRole('checkbox',{name:/The owner has recorded/}).check();
  await page.getByLabel('Property types (one per line)').fill('Apartment\nOffice');
  await page.getByRole('button',{name:'Add reference value',exact:true}).click();
  await page.getByLabel('Reference key',{exact:true}).fill('expense-category');
  await page.getByLabel('Value',{exact:true}).fill('materials');
  await page.getByLabel('Display label',{exact:true}).fill('Materials');
  await page.getByRole('button',{name:'Add inspection checklist',exact:true}).click();
  await page.getByLabel('Checklist name',{exact:true}).fill('Site safety');
  await page.getByLabel('Checks (one per line)',{exact:true}).fill('Access clear\nBarriers present');
  await page.getByRole('button',{name:'Save company settings',exact:true}).click();
  await expect(page.getByText('Company settings saved.')).toBeVisible();
  await expect(page.getByText('Operational setup is incomplete.')).toHaveCount(0);
  await expect(page.getByText('settings.update',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Base currency (ISO code)')).toHaveValue('USD');
  await expect(page.getByLabel('Property types (one per line)')).toHaveValue('Apartment\nOffice');
  await expect(page.getByLabel('Checklist name',{exact:true})).toHaveValue('Site safety');
  const status=page.locator('section').filter({has:page.getByRole('heading',{name:'Local operator status',exact:true})});
  await expect(status.locator('dt').filter({hasText:/^Readiness$/}).locator('+ dd')).toHaveText('Ready');
  await expect(status).toContainText('No successful backup recorded');
  const health=await page.request.get('/api/v1/health/ready');
  expect(health.status()).toBe(200);
  const operator=await page.request.get('/api/v1/operator/status');
  const body=await operator.json();
  expect(body.data.ready).toBe(true);
  expect(body.data.database.status).toBe('ready');
  expect(body.data.attachments.status).toBe('ready');
  expect(JSON.stringify(body)).not.toMatch(/C:\\|password_hash|SQLITE_PATH/);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const identity=(await (await page.request.get('/api/v1/auth/me')).json()).data;
  const acknowledgment=page.getByRole('group',{name:'Record acknowledgment',exact:true});
  await acknowledgment.getByLabel('Subject type').selectOption('user');
  await acknowledgment.getByLabel('Subject ID').fill(identity.user.id);
  await acknowledgment.getByLabel('Privacy notice version',{exact:true}).fill('test-notice-v1');
  await acknowledgment.getByLabel('Acknowledgment time').fill('2026-11-01T10:00');
  await acknowledgment.getByLabel('Evidence / recording reason').fill('Disposable fixture notice accepted');
  await acknowledgment.getByRole('checkbox',{name:'Explicit consent was given'}).check();
  await acknowledgment.getByRole('button',{name:'Record acknowledgment'}).click();
  await expect(page.getByText('Action saved.',{exact:true})).toBeVisible();
  const hold=page.getByRole('group',{name:'Record a legal hold',exact:true});
  await hold.getByLabel('Record type').fill('user');
  await hold.getByLabel('Record ID',{exact:true}).fill(identity.user.id);
  await hold.getByLabel('Hold / release reason').fill('Disposable evidence preservation');
  await hold.getByRole('button',{name:'Create hold',exact:true}).click();
  await expect(page.getByRole('button',{name:/^Release hold /})).toBeVisible();
  const retention=page.getByRole('group',{name:'Prepare a retention review',exact:true});
  await retention.getByLabel('As-of date').fill('2026-11-03');
  await retention.getByRole('button',{name:'Find eligible records'}).click();
  await expect(page.getByText('No eligible records.',{exact:true})).toBeVisible();
});

test('Administrator reviews and completes a staff access request',async ({page,accountServer})=>{
  await page.goto('/login?returnUrl=%2Fsettings');
  await page.getByLabel('Email address').fill(accountServer.email);
  await page.getByLabel('Password',{exact:true}).fill(accountServer.password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Company settings',exact:true})).toBeVisible();
  const identity=(await (await page.request.get('/api/v1/auth/me')).json()).data;
  const request=page.getByRole('group',{name:'Open a request',exact:true});
  await request.getByLabel('Subject type').selectOption('user');
  await request.getByLabel('Subject ID').fill(identity.user.id);
  await request.getByLabel('Request reason').fill('Disposable staff access review');
  await request.getByRole('button',{name:'Create privacy request'}).click();
  await expect(page.getByText('Action saved.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:/^Review request /}).click();
  await page.getByLabel('Review reason',{exact:true}).fill('Identity verified for test access request');
  await page.getByRole('button',{name:'Save review decision'}).click();
  await expect(page.getByRole('button',{name:/^Execute approved request /})).toBeVisible();
  await page.getByRole('checkbox',{name:/I have reviewed the named request/}).check();
  await page.getByRole('button',{name:/^Execute approved request /}).click();
  await expect(page.getByText('access · completed',{exact:true})).toBeVisible();
  await expect(page.locator('article').filter({hasText:'Disposable staff access review'})).toContainText(accountServer.email);
});
