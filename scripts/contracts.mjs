import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { document } from '../docs/api/contract.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const mode = process.argv[2] || 'check';
if (!['generate', 'check', 'validate', '--check', '--write'].includes(mode)) {
  throw new Error('Usage: node scripts/contracts.mjs [generate|check|validate]');
}
const write = ['generate', '--write'].includes(mode);
const openapiPath = path.join(root, 'docs/openapi.yaml');
const typesPath = path.join(root, 'frontend/src/app/core/contracts/generated/api.ts');
const serialized = `${JSON.stringify(document, null, 2)}\n`;

// Fail on unresolved schemas before invoking the third-party validator.
function inspect(value) {
  if (!value || typeof value !== 'object') return;
  if (value.$ref?.startsWith('#/components/schemas/')) {
    const name = value.$ref.split('/').at(-1);
    if (!document.components.schemas[name]) throw new Error(`Unresolved schema ${name}`);
  }
  if (value.type === 'object' && value.properties) {
    for (const name of value.required || []) if (!(name in value.properties)) throw new Error(`Unknown required field ${name}`);
  }
  for (const child of Object.values(value)) inspect(child);
}
inspect(document);
const ids = new Set();
for (const [route, item] of Object.entries(document.paths)) for (const [method, operation] of Object.entries(item)) {
  if (ids.has(operation.operationId)) throw new Error(`Duplicate operation ID ${operation.operationId}`);
  ids.add(operation.operationId);
  if (!operation['x-permission-policy'] || !operation['x-implementation-status']) throw new Error(`Missing policy/status: ${route}`);
  if (method !== 'get') for (const name of ['Idempotency-Key', 'X-CSRF-Token']) {
    if (!operation.parameters.some(p => p.name === name && p.required)) throw new Error(`Missing ${name}: ${route}`);
  }
}

// Compare method/path coverage against all explicitly named paths in the design.
// Standard resource CRUD is additionally checked from its operation flags.
const design = await readFile(path.join(root, '.nexgile/specs/construction-and-property-management/design.md'), 'utf8');
const normalize = p => p.replace(/\{[^}]+\}/g, '{}');
const routeSet = new Set(Object.keys(document.paths).map(normalize));
const section = design.slice(design.indexOf('### Authentication and administration endpoints'), design.indexOf('### Attachment commit and serving'));
for (const [, route] of section.matchAll(/`(\/[a-z][^` ]*)`/g)) {
  if (!routeSet.has(normalize(route))) throw new Error(`Design path missing: ${route}`);
}

let SwaggerParser, openapiTS, astToString;
try {
  ({ default: SwaggerParser } = await import('@apidevtools/swagger-parser'));
  ({ default: openapiTS, astToString } = await import('openapi-typescript'));
} catch (error) {
  throw new Error('Contract tools unavailable. The manifest owner must install pinned @apidevtools/swagger-parser and openapi-typescript at the repository root.', { cause: error });
}
await SwaggerParser.validate(structuredClone(document));
const header = '// Generated by scripts/contracts.mjs using openapi-typescript. Do not edit.\n';
const generated = header + astToString(await openapiTS(structuredClone(document), { alphabetize: true })).replace(/\r\n/g, '\n');
if (mode !== 'validate') {
  if (write) {
    await mkdir(path.dirname(typesPath), { recursive: true });
    await writeFile(openapiPath, serialized);
    await writeFile(typesPath, generated);
  } else {
    for (const [file, expected] of [[openapiPath, serialized], [typesPath, generated]]) {
      const actual = await readFile(file, 'utf8').catch(() => '');
      if (actual.replace(/\r\n/g, '\n') !== expected) throw new Error(`${path.relative(root, file)} is stale. Run node scripts/contracts.mjs generate and retain both generated files.`);
    }
  }
}
console.log(`Contracts ${write ? 'generated' : mode === 'validate' ? 'validated' : 'validated and reproducible'}: ${Object.keys(document.paths).length} paths, ${ids.size} operations, ${Object.keys(document.components.schemas).length} schemas.`);
